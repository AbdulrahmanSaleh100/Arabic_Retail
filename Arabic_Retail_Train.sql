-- ===================== الفئات =====================
CREATE TABLE الفئات (
    رقم_الفئة      SERIAL PRIMARY KEY,
    اسم_الفئة     VARCHAR(100) NOT NULL UNIQUE,
    موسمية         VARCHAR(50),
    هامش_الربح     NUMERIC(5,2)
);

-- ===================== المنتجات =====================
CREATE TABLE المنتجات (
    رقم_المنتج       SERIAL PRIMARY KEY,
    اسم_المنتج      VARCHAR(200) NOT NULL,
    رقم_الفئة        INT NOT NULL REFERENCES الفئات(رقم_الفئة),
    سعر_التكلفة     NUMERIC(10,2) NOT NULL,
    سعر_البيع       NUMERIC(10,2) NOT NULL,
    وحدة_القياس     VARCHAR(30) DEFAULT 'قطعة',
    هو_بيستسيلر     BOOLEAN DEFAULT FALSE
);

-- ===================== الفروع =====================
CREATE TABLE الفروع (
    رقم_الفرع       SERIAL PRIMARY KEY,
    اسم_الفرع      VARCHAR(100) NOT NULL,
    المدينة          VARCHAR(80) NOT NULL,
    المنطقة          VARCHAR(80),
    مستوى_الأداء    VARCHAR(20) CHECK (مستوى_الأداء IN ('ممتاز','جيد','متوسط','ضعيف'))
);

-- ===================== المخزون =====================
CREATE TABLE المخزون (
    رقم_المخزون     SERIAL PRIMARY KEY,
    رقم_المنتج      INT NOT NULL REFERENCES المنتجات(رقم_المنتج),
    رقم_الفرع       INT NOT NULL REFERENCES الفروع(رقم_الفرع),
    الكمية_الحالية  INT NOT NULL DEFAULT 0,
    نقطة_إعادة_الطلب INT NOT NULL DEFAULT 20,
    آخر_تحديث       DATE NOT NULL,
    UNIQUE(رقم_المنتج, رقم_الفرع)
);

-- ===================== العملاء =====================
CREATE TABLE العملاء (
    رقم_العميل      SERIAL PRIMARY KEY,
    اسم_العميل     VARCHAR(150) NOT NULL,
    شريحة_العميل   VARCHAR(20) CHECK (شريحة_العميل IN ('VIP','متوسط','نادر')),
    تاريخ_التسجيل  DATE NOT NULL,
    المدينة          VARCHAR(80),
    النقاط           INT DEFAULT 0
);

-- ===================== الفواتير =====================
CREATE TABLE الفواتير (
    رقم_الفاتورة    SERIAL PRIMARY KEY,
    رقم_العميل      INT NOT NULL REFERENCES العملاء(رقم_العميل),
    رقم_الفرع       INT NOT NULL REFERENCES الفروع(رقم_الفرع),
    تاريخ_الفاتورة  DATE NOT NULL,
    طريقة_الدفع    VARCHAR(30) CHECK (طريقة_الدفع IN ('نقدي','بطاقة','أونلاين')),
    الإجمالي         NUMERIC(12,2) NOT NULL,
    الخصم            NUMERIC(10,2) DEFAULT 0,
    الصافي           NUMERIC(12,2) NOT NULL
);

-- ===================== تفاصيل_الفواتير =====================
CREATE TABLE تفاصيل_الفواتير (
    رقم_التفصيل     SERIAL PRIMARY KEY,
    رقم_الفاتورة    INT NOT NULL REFERENCES الفواتير(رقم_الفاتورة),
    رقم_المنتج      INT NOT NULL REFERENCES المنتجات(رقم_المنتج),
    الكمية           INT NOT NULL,
    سعر_الوحدة      NUMERIC(10,2) NOT NULL,
    الإجمالي         NUMERIC(12,2) NOT NULL
);

